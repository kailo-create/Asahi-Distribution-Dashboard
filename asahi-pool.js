function renderAsahiPool(){
  const body=document.getElementById('asahi-pool-table');
  if(!body)return;
  const rows=ASAHI_POOL_SNAPSHOT.rows
    .map(([sourceRow,id,name,type,city,tier])=>({sourceRow,id,name,type,city,tier}))
    .sort((a,b)=>'ABC'.indexOf(a.tier)-'ABC'.indexOf(b.tier)||a.sourceRow-b.sourceRow);
  const counts=rows.reduce((result,row)=>{result[row.tier]=(result[row.tier]||0)+1;return result;},{});
  document.getElementById('pool-count-a').textContent=counts.A||0;
  document.getElementById('pool-count-b').textContent=counts.B||0;
  document.getElementById('pool-count-c').textContent=counts.C||0;
  document.getElementById('pool-count-held').textContent=ASAHI_POOL_SNAPSHOT.previewRows-rows.length;
  document.getElementById('pool-count-eligible').textContent=rows.length;

  const search=document.getElementById('asahi-pool-search');
  const tierFilter=document.getElementById('asahi-pool-tier');
  const empty=document.getElementById('asahi-pool-empty');
  const resultCount=document.getElementById('asahi-pool-result-count');
  const sourceBase='https://docs.google.com/spreadsheets/d/1Ubzqq_EKfJ8TDvo7KEBRG4KV4anXROxScoZAhPfS2gA/edit?gid=256360687';
  const tierLabels={A:'A｜直接啤酒情境',B:'B｜餐飲搭餐優先',C:'C｜先確認場景'};
  const renderRows=()=>{
    const query=search.value.trim().toLowerCase();
    const visible=rows.filter(row=>(!tierFilter.value||row.tier===tierFilter.value)&&`${row.name} ${row.type} ${row.city}`.toLowerCase().includes(query));
    body.replaceChildren();
    visible.forEach(row=>{
      const tr=document.createElement('tr');
      const tier=document.createElement('td'),badge=document.createElement('span');
      badge.className=`pool-tier-badge tier-${row.tier.toLowerCase()}`;
      badge.textContent=tierLabels[row.tier];
      tier.appendChild(badge);
      const name=document.createElement('td'),strong=document.createElement('strong'),id=document.createElement('small');
      strong.textContent=row.name;id.textContent=`ID ${row.id}`;name.append(strong,id);
      const type=document.createElement('td');type.textContent=row.type||'店型未填（名稱線索分類，請複核）';
      const city=document.createElement('td');city.textContent=row.city||'未提供';
      const next=document.createElement('td'),nextText=document.createElement('span');
      nextText.className='pool-next-step';nextText.textContent='確認酒證、啤酒品牌、決策者與冷藏條件';
      next.appendChild(nextText);
      const source=document.createElement('td'),link=document.createElement('a');
      link.href=`${sourceBase}&range=A${row.sourceRow}`;
      link.target='_blank';link.rel='noopener noreferrer';link.textContent=`第 ${row.sourceRow} 列`;
      source.appendChild(link);
      tr.append(tier,name,type,city,next,source);body.appendChild(tr);
    });
    empty.hidden=visible.length>0;
    resultCount.textContent=`顯示 ${visible.length} / ${rows.length} 家候選 · 快照 ${ASAHI_POOL_SNAPSHOT.capturedAt}`;
  };
  search.addEventListener('input',renderRows);
  tierFilter.addEventListener('change',renderRows);
  document.getElementById('export-asahi-pool').addEventListener('click',()=>{
    const headers=['初篩類別','客戶名稱','來源店型','城市','來源店號','試算表列','下一步確認'];
    const csvRows=rows.map(row=>[tierLabels[row.tier],row.name,row.type,row.city,row.id,row.sourceRow,'酒類資格、啤酒品牌、決策者、冷藏條件']);
    const content=[headers,...csvRows].map(row=>row.map(value=>`"${String(value).replace(/"/g,'""')}"`).join(',')).join('\r\n');
    const blob=new Blob(['\uFEFF',content],{type:'text/csv;charset=utf-8'});
    const url=URL.createObjectURL(blob),anchor=document.createElement('a');
    anchor.href=url;anchor.download='asahi-customer-pool-first-pass.csv';anchor.click();
    URL.revokeObjectURL(url);
  });
  renderRows();
}

document.addEventListener('DOMContentLoaded',renderAsahiPool);
